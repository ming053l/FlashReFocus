#!/usr/bin/env python
"""LaTeX appendix table: bokeh rendering on the RealBokeh validation split (Table-3 metrics without LVCorr).
Full-reference metrics come from eval_bokeh_table.py (per-image CSVs, results_rbval/<method>_rbval.csv), no-reference
ones from score_folders.py (results_rbval/nr_*.json on all pairs, nr_sub10.json on the GenRefocus subset, keys 1-10).
Methods that have not finished all pairs are printed as running.
usage: make_rbval_table.py <out.tex>"""
import csv
import json
import sys
from pathlib import Path

R = Path(__file__).resolve().parent / "results_rbval"
N_ALL, SUB = 219, [str(i) for i in range(1, 11)]
FR = ["psnr", "ssim", "ms_ssim", "lpips", "lpips_vgg", "dists"]
NR = ["clip_i", "clipiqa", "musiq", "maniqa"]
LOWER = {"lpips", "lpips_vgg", "dists"}
FMT = {"psnr": "{:.2f}", "musiq": "{:.2f}"}
MAIN = [("DeepLens", r"DeepLens \textit{(TOG'18)}~\cite{deeplens}"),
        ("BokehMe", r"BokehMe \textit{(CVPR'22)}~\cite{bokehme}"),
        ("Bokehlicious", r"Bokehlicious$^{\#\dagger}$ \textit{(ICCV'25)}~\cite{bokehlicious}"),
        ("BokehDiff", r"BokehDiff$^\#$ \textit{(ICCV'25)}~\cite{bokehdiff}"),
        ("MagicBokeh", r"MagicBokeh \textit{(CVPR'26)}~\cite{magicbokeh}"),
        ("DeReFocus-bf16", r"\textbf{\method{}}$^\dagger$")]
SUBSET = [("GenRefocus", r"GenRefocus \textit{(arXiv'25)}~\cite{genrefocus}"), ("DeReFocus-bf16", r"\textbf{\method{}}$^\dagger$")]


def fr_rows(m):
    p = R / f"{m}_rbval.csv"
    return {r["key"]: r for r in csv.DictReader(open(p))} if p.exists() else {}


def nr_all():
    out = {}
    for p in sorted(R.glob("nr_*.json")):
        if p.name != "nr_sub10.json":
            for m, v in json.loads(p.read_text()).items():
                out[m] = v
    return out


def scores(m, keys, nr):
    rows = fr_rows(m)
    if not all(k in rows for k in keys) or nr.get(m, {}).get("n", 0) != len(keys):
        return None
    s = {c: sum(float(rows[k][c]) for k in keys) / len(keys) for c in FR}
    s.update({c: nr[m][c] for c in NR})
    return s


def block(methods, keys, nr, ranks):
    vals = {m: scores(m, keys, nr) for m, _ in methods}
    done = [m for m in vals if vals[m] is not None]
    lines = []
    for m, label in methods:
        if vals[m] is None:
            lines.append(f"{label}\n& \\multicolumn{{10}}{{c}}{{\\textit{{running}}}}\\\\")
            continue
        cells = []
        for c in FR + NR:
            order = sorted(done, key=lambda x: vals[x][c] if c in LOWER else -vals[x][c])
            r = order.index(m)
            tag = ranks[r] + " " if r < len(ranks) else ""
            cells.append(tag + FMT.get(c, "{:.4f}").format(vals[m][c]))
        lines.append(f"{label}\n& " + " & ".join(cells) + "\\\\")
    return lines


def main():
    nr = nr_all()
    sub = json.loads((R / "nr_sub10.json").read_text()) if (R / "nr_sub10.json").exists() else {}
    keys_all = [str(i) for i in range(1, N_ALL + 1)]
    have = fr_rows("DeReFocus-bf16")
    keys_all = sorted(have, key=int) if len(have) == N_ALL else keys_all
    body = block(MAIN, keys_all, nr, [r"\rankA", r"\rankB", r"\rankC"])
    body_sub = block(SUBSET, SUB, sub, [r"\rankA"])
    tex = r"""% Appendix table: bokeh rendering on the RealBokeh validation split (generated by bokeh_eval_import/make_rbval_table.py).
\begin{table*}[t]
\centering
\caption{\textbf{Bokeh rendering on RealBokeh validation.} 219 pairs from $f/22$ to $f/2.0$ at the original $2000\times1500$ resolution, with the annotated focal points and the protocol of Table~\mainref{tab:bokeh_comparison}{3}. Darker green marks the best, second, and third results. GenRefocus takes about an hour per image at this resolution and is compared with \method{} on the first 10 pairs (bottom). MPIB and Dr.Bokeh are not evaluated. $^\#$\,Selects its own focal region. $^\dagger$\,Trained on the RealBokeh training split (same cameras and lenses), hence not zero-shot.}
\label{tab:bokeh_realbokeh}
\scriptsize\setlength{\tabcolsep}{2pt}
\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lcccccccccc@{}}
\toprule
\multirow{2}{*}{Methods}
& \multicolumn{7}{c}{Full-reference Metrics}
& \multicolumn{3}{c}{No-reference IQA Metrics} \\
\cmidrule(lr){2-8}
\cmidrule(lr){9-11}
 & PSNR$\uparrow$ & SSIM$\uparrow$ & MS-SSIM$\uparrow$ & LPIPS$\downarrow$ & LPIPS$_\text{VGG}$$\downarrow$ & DISTS$\downarrow$ & CLIP-I$\uparrow$ & CLIP-IQA$\uparrow$ & MUSIQ$\uparrow$ & MANIQA$\uparrow$ \\
\midrule
\multicolumn{11}{l}{\textit{All 219 pairs}}\\
\midrule
""" + "\n".join(body) + r"""
\midrule[\heavyrulewidth]
\multicolumn{11}{l}{\textit{First 10 pairs}}\\
\midrule
""" + "\n".join(body_sub) + r"""
\bottomrule
\end{tabular*}
\end{table*}
"""
    Path(sys.argv[1]).write_text(tex)
    print(tex)


if __name__ == "__main__":
    main()
